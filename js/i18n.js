  const STORAGE = "ta-lang";
  const codes = langs.map((l) => l.code);

  const pick = () => {
    const saved = localStorage.getItem(STORAGE);
    if (codes.includes(saved)) return saved;
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    if (nav === "ua") return "uk";
    return codes.includes(nav) ? nav : "en";
  };

  let extra = {};

  const t = (lang, key) =>
    (extra[lang] && extra[lang][key]) ||
    (dict[lang] && dict[lang][key]) ||
    (extra.en && extra.en[key]) ||
    dict.en[key] ||
    "";

  const apply = (lang) => {
    if (!codes.includes(lang)) lang = "en";
    localStorage.setItem(STORAGE, lang);
    document.documentElement.lang = lang === "uk" ? "uk" : lang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const val = t(lang, el.getAttribute("data-i18n"));
      if (val) el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const val = t(lang, el.getAttribute("data-i18n-html"));
      if (val) el.innerHTML = val;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const val = t(lang, el.getAttribute("data-i18n-placeholder"));
      if (val) el.setAttribute("placeholder", val);
    });
    document.querySelectorAll("[data-i18n-content]").forEach((el) => {
      const val = t(lang, el.getAttribute("data-i18n-content"));
      if (val) el.setAttribute("content", val);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      const val = t(lang, el.getAttribute("data-i18n-alt"));
      if (val) el.setAttribute("alt", val);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const val = t(lang, el.getAttribute("data-i18n-aria"));
      if (val) el.setAttribute("aria-label", val);
    });
    document.querySelectorAll("[data-i18n-cursor]").forEach((el) => {
      const val = t(lang, el.getAttribute("data-i18n-cursor"));
      if (val) el.setAttribute("data-cursor", val);
    });

    const current = langs.find((l) => l.code === lang);
    document.querySelectorAll("[data-lang-current]").forEach((el) => {
      el.textContent = current ? current.short : "EN";
    });
    document.querySelectorAll("[data-lang-set]").forEach((btn) => {
      btn.classList.toggle("is-active", btn.getAttribute("data-lang-set") === lang);
    });

    protectBrandCasing();
  };

  const protectBrandCasing = () => {
    if (!document.body) return;
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        if (parent.classList.contains("brand-mixed")) return NodeFilter.FILTER_REJECT;
        if (parent.closest("script, style, textarea, code")) return NodeFilter.FILTER_REJECT;
        if (!node.nodeValue || !/MicBioMate/i.test(node.nodeValue)) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      const parts = node.nodeValue.split(/MicBioMate/i);
      const frag = document.createDocumentFragment();
      parts.forEach((part, i) => {
        if (part) frag.appendChild(document.createTextNode(part));
        if (i < parts.length - 1) {
          const mark = document.createElement("span");
          mark.className = "brand-mixed";
          mark.textContent = "MicBioMate";
          frag.appendChild(mark);
        }
      });
      node.parentNode.replaceChild(frag, node);
    });
  };

